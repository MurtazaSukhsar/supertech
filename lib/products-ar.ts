/**
 * Arabic translations for the product catalogue.
 *
 * Kept in a separate file from `products.ts` so the English source of truth
 * (ids, images, specs structure) stays untouched. Anything missing here falls
 * back to the English string, so a new product added to `products.ts` still
 * renders on the Arabic site until it gets translated.
 *
 * Conventions used throughout:
 *  - Trade brand names (Fischer, Shurtape, Aeroduct, GoFlex…) stay in Latin.
 *  - Standards codes (ASTM B280, BS 4568, IEC 60900…) stay in Latin.
 *  - Imperial/metric measurements and part sizes stay in Western digits, which
 *    is what Kuwaiti trade documents and technicians actually use.
 */

